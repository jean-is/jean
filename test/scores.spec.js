test('before Skills is found, `skill`’s line names Jean’s own, and the brain reading Music score finds Skills, adds it and draws the tune (D406)', async ({ page }) => {
  await start(page)
  await connectFakeBrain(page)
  const unlocked = () => page.evaluate(async () => (await import('/ui/state.js')).app.settings.value.unlocked.includes('skills'))
  expect(await unlocked()).toBe(false)
  await ask(page, 'Compose une courte berceuse, en partition que je peux jouer.')
  await expect(page.locator('.toast')).toContainText('Saved the skill “Music score”.')
  await expect(page.locator('.msg-jean app-score .score-sheet svg')).toHaveCount(1)
  await expect(page.locator('.msg-jean .prose').last()).toContainText('Play it lightly.')
  expect(await unlocked()).toBe(true)
  expect(await page.evaluate(async () => (await (await import('/caps/skills/skills.js')).skills()).map((skill) => skill.name))).toEqual(['music-score'])
  const prompt = await page.evaluate(async () => (await import('/ui/state.js')).app.current.value?.records.find((record) => record.meta?.prompt)?.meta?.prompt)
  expect(prompt.system).toMatch(/\n- skill: read the steps of a skill before following it: plain-words, letter, [^\n]*\bmusic-score\b/)
  expect(prompt.system).not.toContain('<skills>')
  expect(prompt.system).not.toContain('When a request matches a skill')
  expect(prompt.state.tools).toContain('skill')
  expect(prompt.state.tools).not.toContain('save_skill')
  // The prompt stays as the brain read it: the next message brings Skills' list in a note, its other tools deferred.
  await expect.poll(() => page.evaluate(async () => (await import('/ui/state.js')).app.busy.value)).toBe(false)
  await ask(page, 'Thank you')
  await expect(page.locator('.msg-jean')).toHaveCount(2)
  await expect.poll(() => page.evaluate(async () => (await import('/ui/state.js')).app.busy.value)).toBe(false)
  const records = JSON.stringify(await page.evaluate(async () => (await import('/ui/state.js')).app.current.value?.records))
  expect(records).toContain('The <skills> section is now')
  expect(records).toContain('save_skill')
})

test('the tunes answers hold are among the creations, each drawn on its card and opening beside the task, playing, and New score asks for one in the box with Music score (D542, D544)', async ({ page }) => {
  await start(page)
  await connectFakeBrain(page)
  await turnOn(page, 'Skills')
  await page.keyboard.press('Escape')
  const tasks = await openTasks(page)
  const place = tasks.getByRole('button', { name: 'Creations', exact: true })
  await place.click()
  const creations = page.locator('app-creations')
  await expect(creations.locator('.creation')).toHaveCount(0)
  // New score: Jean's own Music score in the room, and a request in the box, its example selected for the user's own words.
  await creations.getByRole('button', { name: 'New score', exact: true }).click()
  const box = page.locator('#prompt')
  await expect(box).toBeFocused()
  await expect(box).toHaveValue('Compose a short lullaby for the piano, as sheet music I can play.')
  expect(await box.evaluate((/** @type {HTMLTextAreaElement} */ area) => area.value.slice(area.selectionStart, area.selectionEnd))).toBe('a short lullaby for the piano')
  expect(await page.evaluate(async () => (await (await import('/caps/skills/skills.js')).skills()).map((skill) => skill.name))).toEqual(['music-score'])
  await page.keyboard.type('a jig')
  await page.keyboard.press('Enter')
  await expect(page.locator('.msg-jean app-score .score-sheet svg')).toHaveCount(1)
  await expect(creations).toHaveCount(0)
  // On its card, named by its title, the score drawn; picked, its task opens, where it plays.
  await place.click()
  const card = creations.locator('.creation')
  await expect(card.locator('.creation-open')).toHaveText(['The Legacy Jig'])
  await expect(card.locator('.creation-preview app-score .score-sheet svg')).toHaveCount(1)
  await expect(card.locator('.creation-preview .score-player')).toBeHidden()
  // Picked, it opens beside the task, its player on top, playing at once (D544).
  await card.click()
  const beside = page.locator('app-preview app-score')
  await expect(beside.locator('.score-sheet svg')).toHaveCount(1)
  await expect(beside.getByRole('button', { name: 'Pause' })).toBeVisible()
  expect(await beside.evaluate((score) => /** @type {Element} */ (score.querySelector('.score-player')).getBoundingClientRect().top < /** @type {Element} */ (score.querySelector('.score-sheet')).getBoundingClientRect().top)).toBe(true)
  await expect(page.locator('app-preview .pane-head h2')).toHaveText('The Legacy Jig.abc')
  await expect(creations).toBeVisible()
})

test('a tune is renamed and pinned by a record in its task, and taken off the Creations page while its answer keeps it (D544)', async ({ page }) => {
  await start(page)
  await connectFakeBrain(page)
  await turnOn(page, 'Skills')
  await page.keyboard.press('Escape')
  const tasks = await openTasks(page)
  const place = tasks.getByRole('button', { name: 'Creations', exact: true })
  await place.click()
  const creations = page.locator('app-creations'), card = creations.locator('.creation')
  await creations.getByRole('button', { name: 'New score', exact: true }).click()
  await expect(page.locator('#prompt')).toHaveValue('Compose a short lullaby for the piano, as sheet music I can play.')
  await page.keyboard.type('a jig')
  await page.keyboard.press('Enter')
  await expect(page.locator('.msg-jean app-score .score-sheet svg')).toHaveCount(1)
  await place.click()
  await expect(card.locator('.creation-open')).toHaveText(['The Legacy Jig'])
  const menu = async () => { await card.click({ button: 'right' }); return creations.locator('.task-menu:popover-open') }
  await (await menu()).getByRole('button', { name: 'Rename' }).click()
  await page.keyboard.type('Jig for Léa')
  await page.keyboard.press('Enter')
  await (await menu()).getByRole('button', { name: 'Pin' }).click()
  await expect(creations.locator('.creations-group')).toHaveText(['Pinned1'])
  await expect(card.locator('.creation-open')).toHaveText(['Jig for Léa'])
  // Read again from its task, as after a reload (which Playwright's WebKit, keeping nothing, can't show).
  const tunes = () => page.evaluate(async () => (await (await import('/ui/creations.js')).creationsHere()).map((one) => `${one.name}${one.pinned ? ' (pinned)' : ''}`))
  await expect.poll(tunes).toEqual(['Jig for Léa (pinned)'])
  await (await menu()).getByRole('button', { name: 'Another like this' }).click()
  await expect(page.locator('#prompt')).toHaveValue('Compose a tune like “Jig for Léa”, but ')
  await page.locator('#prompt').fill('')
  await (await menu()).getByRole('button', { name: 'Remove from Creations' }).click()
  await expect(page.locator('.toast')).toContainText('“Jig for Léa” removed from Creations.')
  await expect(card).toHaveCount(0)
  await expect.poll(tunes, { timeout: 8000 }).toEqual([])
  // Its answer is as it was.
  await tasks.locator('.history-item').first().click()
  await expect(page.locator('.msg-jean app-score .score-sheet')).toHaveAttribute('aria-label', 'The Legacy Jig')
})
